package com.example.dexplorer.core.util

import java.io.File
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

object FileTemplateCreator {

    fun createFromExtension(file: File) {
        when (file.extension.lowercase()) {
            "docx" -> createDocx(file)
            "xlsx" -> createXlsx(file)
            "pptx" -> createPptx(file)
            else   -> file.createNewFile()
        }
    }

    // ── DOCX ──────────────────────────────────────────────────────────────────

    private fun createDocx(file: File) = zip(file) {
        entry("[Content_Types].xml", """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>
</Types>""")
        entry("_rels/.rels", """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>
</Relationships>""")
        entry("word/document.xml", """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
  <w:body><w:p/></w:body>
</w:document>""")
        entry("word/_rels/document.xml.rels", """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"/>""")
    }

    // ── XLSX ──────────────────────────────────────────────────────────────────

    private fun createXlsx(file: File) = zip(file) {
